# Rendering
# ---------------------------------------------------------------------------

def link(target: str, from_dir: str) -> str:
    """Relative link from a page in `from_dir` (repo-relative) to `target`."""
    return Path(os.path.relpath(ROOT / target, ROOT / from_dir)).as_posix()


def plural(n: int, word: str) -> str:
    return f"{n} {word}" + ("" if n == 1 else "s")


def status_line(status: dict) -> str:
    parts = [REVIEW[status["review"]]]
    if status["formalization"] == "none":
        parts.append(FORMALIZATION["none"])
    else:
        parts.append(f"{FORMALIZATION[status['formalization']]} ({status['formalization_system']})")
    parts.append(COMMUNITY[status["community"]])
    return " · ".join(parts)


def problem_cell(paper: dict, problems: dict, from_dir: str) -> str:
    cells = []
    for m in paper["millennium"]:
        page = link(f"problems/{m['problem']}.md", from_dir)
        cells.append(f"[{problems[m['problem']]['name']}]({page}) ({m['relation']})")
    return "<br>".join(cells) if cells else "—"


def paper_table(papers: list[dict], problems: dict, from_dir: str, *, with_problem: bool) -> str:
    head = "| Date | Paper | " + ("Millennium problem | " if with_problem else "") + "Status |"
    sep = "|---|---|" + ("---|" if with_problem else "") + "---|"
    rows = [head, sep]
    for p in papers:
        title = f"**[{p['title']}]({link(p['path'], from_dir)}/)**"
        authors = ", ".join(p["authors"])
        cell = f"{title}<br>{authors} — {p['tldr']}"
        row = f"| {p['date']} | {cell} | "
        if with_problem:
            row += problem_cell(p, problems, from_dir) + " | "
        row += status_line(p["status"]) + " |"
        rows.append(row)
    return "\n".join(rows)


def render_readme_sections(problems: dict, papers: list[dict], backlog: list[dict]) -> dict[str, str]:
    per_problem = defaultdict(lambda: defaultdict(int))
    queued = defaultdict(int)
    for p in papers:
        for m in p["millennium"]:
            per_problem[m["problem"]][m["relation"]] += 1
    for b in backlog:
        for m in b["millennium"]:
            queued[m["problem"]] += 1
    rows = ["| Problem | Status | Explained here | Queued |", "|---|---|---|---|"]
    for pid, prob in problems.items():
        counts = per_problem[pid]
        explained = ", ".join(f"{counts[r]} {r}" for r in RELATIONS if counts[r]) or "—"
        rows.append(f"| [{prob['name']}](problems/{pid}.md) | {prob['status_note']} | "
                    f"{explained} | {queued[pid] or '—'} |")
    problems_md = "\n".join(rows)

    latest = sorted(papers, key=lambda p: (p["explainer"]["added"], p["date"]), reverse=True)[:10]
    lines = []
    for p in latest:
        rel = ", ".join(f"{problems[m['problem']]['name']} ({m['relation']})" for m in p["millennium"])
        extras = []
        if p["explainer"].get("video") or p["explainer"].get("video_url"):
            extras.append("video")
        if p["explainer"].get("code"):
            extras.append("code")
        extra = f" · {' + '.join(['explainer'] + extras)}" if extras else ""
        lines.append(f"- **[{p['title']}]({p['path']}/)** ({p['date']}) — {p['tldr']}  \n"
                     f"  *{rel or 'Not tied to a Millennium problem'} · {status_line(p['status'])}{extra}*")
    latest_md = "\n".join(lines) if lines else "_No explainers yet._"
    stats_md = (f"**{len(papers)}** explained paper{'s' if len(papers) != 1 else ''} · "
                f"**{len(backlog)}** queued · catalog regenerated by `tools/catalog.py`")
    return {"problems": problems_md, "latest": latest_md, "stats": stats_md}


def render_problem_sections(pid: str, problems: dict, papers: list[dict],
                            backlog: list[dict]) -> dict[str, str]:
    from_dir = "problems"
    mine = [p for p in papers if any(m["problem"] == pid for m in p["millennium"])]
    blocks = []
    for rel, heading in RELATIONS.items():
        group = [p for p in mine if any(m["problem"] == pid and m["relation"] == rel
                                        for m in p["millennium"])]
        if not group:
            continue
        blocks.append(f"### {heading}\n\n*Papers that {RELATION_HELP[rel]}.*\n\n"
                      + paper_table(group, problems, from_dir, with_problem=False))
        notes = []
        for p in group:
            for m in p["millennium"]:
                if m["problem"] == pid and m["note"]:
                    notes.append(f"- *{p['short_title']}*: {m['note']}")
        if notes:
            blocks[-1] += "\n\n" + "\n".join(notes)
    papers_md = "\n\n".join(blocks) if blocks else "_No explainers yet — see the queue below._"

    items = [b for b in backlog if any(m["problem"] == pid for m in b["millennium"])]
    lines = []
    order = {rel: i for i, rel in enumerate(RELATIONS)}

    def relation_of(b: dict) -> str:
        return next(m["relation"] for m in b["millennium"] if m["problem"] == pid)

    items.sort(key=lambda b: b["date"], reverse=True)
    for b in sorted(items, key=lambda b: order[relation_of(b)]):  # stable: newest first per relation
        relation = relation_of(b)
        extra = "".join(f" · [{l['label']}]({l['url']})" for l in b["links"])
        authors = ", ".join(b["authors"])
        lines.append(f"- **[{b['title']}]({b['url']})** — {authors}, {b['date']} · *{relation}*{extra}  \n"
                     f"  {b['note']}")
    backlog_md = ("\n".join(lines) if lines else "_Nothing queued._")
    return {"papers": papers_md, "backlog": backlog_md}


def render_catalog(problems: dict, papers: list[dict]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    by_year = defaultdict(list)
    for p in papers:
        by_year[p["date"][:4]].append(p)
    tags = defaultdict(list)
    for p in papers:
        for t in p["tags"]:
            tags[t].append(p)

    lines = [GENERATED_NOTE, "", "# Catalog", "",
             f"{plural(len(papers), 'explained paper')}. Browse by year or by tag; "
             "[`papers.json`](papers.json) has every field for scripts.", "",
             "## By year", "", "| Year | Papers |", "|---|---|"]
    for year in sorted(by_year, reverse=True):
        lines.append(f"| [{year}]({year}.md) | {len(by_year[year])} |")
    lines += ["", "## By Millennium problem", ""]
    for pid, prob in problems.items():
        n = sum(1 for p in papers if any(m["problem"] == pid for m in p["millennium"]))
        lines.append(f"- [{prob['name']}](../problems/{pid}.md) — {n}")
    lines += ["", "## By tag", "",
              " · ".join(f"[{t}](tags.md#{t}) ({len(tags[t])})" for t in sorted(tags)) or "—", ""]
    out[CATALOG / "README.md"] = "\n".join(lines)

    for year, items in by_year.items():
        lines = [GENERATED_NOTE, "", f"# {year}", "", f"[← Catalog](README.md) · {plural(len(items), 'paper')}", ""]
        by_month = defaultdict(list)
        for p in items:
            by_month[p["date"][5:7]].append(p)
        for month in sorted(by_month, reverse=True):
            name = dt.date(int(year), int(month), 1).strftime("%B")
            lines += [f"## {name}", "", paper_table(by_month[month], problems, "catalog", with_problem=True), ""]
        out[CATALOG / f"{year}.md"] = "\n".join(lines)

    lines = [GENERATED_NOTE, "", "# Papers by tag", "", "[← Catalog](README.md)", ""]
    for t in sorted(tags):
        lines += [f"## {t}", ""]
        for p in tags[t]:
            lines.append(f"- [{p['title']}]({link(p['path'], 'catalog')}/) ({p['date']})")
        lines.append("")
    out[CATALOG / "tags.md"] = "\n".join(lines)

    out[CATALOG / "papers.json"] = json.dumps(papers, indent=2, ensure_ascii=False) + "\n"
    return out


def replace_sections(text: str, sections: dict[str, str], where: str) -> str:
    for name, body in sections.items():
        pattern = re.compile(rf"(<!-- BEGIN:{name} -->\n)(.*?)(<!-- END:{name} -->)", re.S)
        if not pattern.search(text):
            raise ValidationError(f"{where}: missing <!-- BEGIN:{name} --> / <!-- END:{name} --> markers")
        text = pattern.sub(lambda m: m.group(1) + body.rstrip("\n") + "\n" + m.group(3), text)
    return text


def render_all() -> dict[Path, str]:
    problems, papers, backlog = load_all()
    md_errors = lint_markdown()
    if md_errors:
        raise ValidationError("markdown problems (GitHub math, broken links):\n" + "\n".join(md_errors))
    out: dict[Path, str] = {}
    readme = ROOT / "README.md"
    out[readme] = replace_sections(readme.read_text(encoding="utf-8"),
                                   render_readme_sections(problems, papers, backlog), "README.md")
    for pid in problems:
        page = PROBLEMS_DIR / f"{pid}.md"
        out[page] = replace_sections(page.read_text(encoding="utf-8"),
                                     render_problem_sections(pid, problems, papers, backlog),
                                     page.relative_to(ROOT).as_posix())
    out.update(render_catalog(problems, papers))
    return out


