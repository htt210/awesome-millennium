MATH_SPAN = re.compile(r"\$\$(.+?)\$\$|\$([^$\n]+?)\$", re.S)


def lint_math(path: Path) -> tuple[list[str], list[str]]:
    """GitHub runs its markdown parser before MathJax, so inside $...$ and
    $$...$$ it deletes a backslash before any non-letter (\\, \\{ \\# ...) and may
    read _ or * as emphasis. ```math blocks and code spans are left alone."""
    text = re.sub(r"```.*?```", "", path.read_text(encoding="utf-8"), flags=re.S)
    text = re.sub(r"`[^`\n]*`", "", text)
    errors, warnings = [], []
    where = path.relative_to(ROOT).as_posix()
    for match in MATH_SPAN.finditer(text):
        math = match.group(1) or match.group(2)
        line = text.count("\n", 0, match.start()) + 1
        snippet = math.strip().replace("\n", " ")[:60]
        bad = re.search(r"\\[^A-Za-z]", math)
        if bad:
            errors.append(f"{where}:{line}: '{bad.group()}' in ${snippet}$ (GitHub drops the backslash; "
                          "use \\lbrace, \\rbrace, drop manual spacing, or a ```math block)")
        if "*" in math:
            errors.append(f"{where}:{line}: '*' in ${snippet}$ (use \\ast)")
        if re.search(r"[)\]}]_", math):
            warnings.append(f"{where}:{line}: subscript after a bracket in ${snippet}$ "
                            "(markdown may read '_' as emphasis; rephrase or use a ```math block)")
        if re.search(r"<\S|\S>", math):
            warnings.append(f"{where}:{line}: '<' or '>' in ${snippet}$ (prefer \\lt and \\gt)")
    return errors, warnings


LINK_RE = re.compile(r"\]\(([^)\s]+)\)|(?:src|href|srcset)=\"([^\"]+)\"")


def broken_links(path: Path) -> list[str]:
    """Relative links and image sources that point at missing files."""
    text = re.sub(r"```.*?```", "", path.read_text(encoding="utf-8"), flags=re.S)
    errors = []
    for match in LINK_RE.finditer(text):
        target = match.group(1) or match.group(2)
        if target.startswith(("http://", "https://", "#", "mailto:")):
            continue
        if not (path.parent / target.split("#")[0]).exists():
            line = text.count("\n", 0, match.start()) + 1
            errors.append(f"{path.relative_to(ROOT).as_posix()}:{line}: broken link {target}")
    return errors


def markdown_files() -> list[Path]:
    out = []
    for path in sorted(ROOT.rglob("*.md")):
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith((".git/", "catalog/")) or "/build/" in rel or "/node_modules/" in rel:
            continue
        out.append(path)
    return out


def lint_markdown() -> list[str]:
    """GitHub-math lint (errors and warnings) plus broken relative links."""
    errors = []
    for path in markdown_files():
        errs, warns = lint_math(path)
        errors += errs
        for w in warns:
            print(f"warning: {w}", file=sys.stderr)
        if not path.relative_to(ROOT).as_posix().startswith("templates/"):
            errors += broken_links(path)
    return errors


def stale_files(outputs: dict[Path, str]) -> list[Path]:
    stale = [path for path, content in outputs.items()
             if not path.exists() or path.read_text(encoding="utf-8") != content]
    expected = set(outputs)
    for path in CATALOG.glob("*"):
        if path.is_file() and path not in expected:
            stale.append(path)  # left over from a removed year
    return stale


def cmd_build(_: argparse.Namespace) -> int:
    outputs = render_all()
    changed = stale_files(outputs)
    CATALOG.mkdir(exist_ok=True)
    for path in changed:
        if path in outputs:
            path.write_text(outputs[path], encoding="utf-8")
        else:
            path.unlink()
    for path in changed:
        print(f"updated {path.relative_to(ROOT).as_posix()}")
    print(f"catalog ok: {len(outputs)} generated files, {len(changed)} changed")
    return 0


def cmd_check(_: argparse.Namespace) -> int:
    outputs = render_all()
    stale = stale_files(outputs)
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT).as_posix()}", file=sys.stderr)
        print("run `python tools/catalog.py build` and commit the result", file=sys.stderr)
        return 1
    print(f"catalog ok: {len(outputs)} generated files up to date")
    return 0


def cmd_run_checks(args: argparse.Namespace) -> int:
    """Run the verification commands each paper declares in explainer.checks,
    from the paper's directory (e.g. the toy implementation's self-test)."""
    _, papers, _ = load_all()
    failures = 0
    for p in papers:
        if args.slug and p["slug"] not in args.slug:
            continue
        for command in p["explainer"].get("checks") or []:
            argv = shlex.split(command)
            if argv and argv[0] in ("python", "python3"):
                argv[0] = sys.executable
            print(f"[{p['slug']}] $ {command}", flush=True)
            result = subprocess.run(argv, cwd=ROOT / p["path"])
            if result.returncode != 0:
                failures += 1
                print(f"[{p['slug']}] FAILED with exit code {result.returncode}", file=sys.stderr)
    print("all paper checks passed" if failures == 0 else f"{failures} check(s) failed")
    return 1 if failures else 0


def cmd_new(args: argparse.Namespace) -> int:
    date = as_date(args.date, "--date")
    require(SLUG_RE.match(args.slug) is not None, "--slug: expected lowercase-kebab-case")
    target = PAPERS / f"{date.year:04d}" / f"{date.month:02d}" / args.slug
    require(not target.exists(), f"{target.relative_to(ROOT)} already exists")
    existing = {p.parent.name for p in PAPERS.glob("*/*/*/paper.yaml")}
    require(args.slug not in existing, f"slug {args.slug!r} is already used")
    target.mkdir(parents=True)
    for src in TEMPLATE.rglob("*"):
        dst = target / src.relative_to(TEMPLATE)
        if src.is_dir():
            dst.mkdir(exist_ok=True)
            continue
        text = src.read_text(encoding="utf-8")
        for key, value in {"slug": args.slug, "title": args.title, "date": date.isoformat(),
                           "today": dt.date.today().isoformat()}.items():
            text = text.replace("{{" + key + "}}", value)
        dst.write_text(text, encoding="utf-8")
    print(f"created {target.relative_to(ROOT).as_posix()}/ — fill in paper.yaml and README.md, "
          "then run `python tools/catalog.py build`")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Validate metadata and regenerate indexes.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build", help="validate and regenerate").set_defaults(func=cmd_build)
    sub.add_parser("check", help="validate and fail if generated files are stale").set_defaults(func=cmd_check)
    run = sub.add_parser("run-checks", help="run the verification commands declared by papers")
    run.add_argument("slug", nargs="*", help="only these papers (default: all)")
    run.set_defaults(func=cmd_run_checks)
    new = sub.add_parser("new", help="scaffold a new paper directory from templates/paper")
    new.add_argument("--date", required=True, help="date of the paper version (YYYY-MM-DD)")
    new.add_argument("--slug", required=True, help="lowercase-kebab-case identifier")
    new.add_argument("--title", required=True)
    new.set_defaults(func=cmd_new)
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except ValidationError as exc:
        print(f"error:\n{exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
