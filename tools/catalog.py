#!/usr/bin/env python3
"""Catalog tool for awesome-millennium.

Every explained paper lives in ``papers/<YYYY>/<MM>/<slug>/`` next to a
``paper.yaml`` metadata file.  This script validates all metadata and
regenerates every index, so the repository stays navigable at thousands of
papers without hand-maintained lists:

    README.md               sections between <!-- BEGIN:x --> / <!-- END:x --> markers
    problems/<id>.md        explained and queued papers for each Millennium problem
    catalog/README.md       entry point: years, tags, machine-readable index
    catalog/<YYYY>.md       every paper of one year, by month
    catalog/tags.md         papers by tag
    catalog/papers.json     machine-readable index of all metadata

Usage:
    python tools/catalog.py build     validate, then regenerate (run before committing)
    python tools/catalog.py check     validate, and fail if a generated file is stale (CI)
    python tools/catalog.py new --date 2026-10-25 --slug eth-is-false \\
        --title "The Exponential Time Hypothesis is False"
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import shlex
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install -r tools/requirements.txt")

ROOT = Path(__file__).resolve().parents[1]
PAPERS = ROOT / "papers"
CATALOG = ROOT / "catalog"
PROBLEMS_DIR = ROOT / "problems"
TEMPLATE = ROOT / "templates" / "paper"

RELATIONS = {
    "resolves": "Claimed resolutions",
    "partial": "Partial results",
    "adjacent": "Adjacent results",
}
RELATION_HELP = {  # completes "Papers that ..."
    "resolves": "claim to settle the problem as stated by the Clay Institute",
    "partial": "prove a special case or a significant piece of the problem",
    "adjacent": "settle a closely related question in the problem's landscape without deciding it",
}
REVIEW = {"preprint": "Preprint", "under-review": "Under journal review",
          "peer-reviewed": "Peer reviewed", "withdrawn": "Withdrawn"}
FORMALIZATION = {"none": "Not formalized", "partial": "Partly formalized",
                 "complete": "Formalized"}
COMMUNITY = {"unexamined": "Not yet examined", "under-examination": "Under examination",
             "accepted": "Accepted", "disputed": "Disputed", "refuted": "Refuted"}

SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
URL_RE = re.compile(r"^https?://\S+$")
GENERATED_NOTE = "<!-- Generated by tools/catalog.py from paper.yaml files. Do not edit by hand. -->"


class ValidationError(Exception):
    pass


# ---------------------------------------------------------------------------
# Loading and validation
# ---------------------------------------------------------------------------

def load_yaml(path: Path):
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def as_date(value, where: str) -> dt.date:
    if isinstance(value, dt.date):
        return value
    try:
        return dt.date.fromisoformat(str(value))
    except ValueError:
        raise ValidationError(f"{where}: expected a YYYY-MM-DD date, got {value!r}")


def require(cond: bool, msg: str) -> None:
    if not cond:
        raise ValidationError(msg)


def check_text(value, where: str, *, table_safe: bool = False) -> str:
    require(isinstance(value, str) and value.strip() != "", f"{where}: expected non-empty text")
    if table_safe:
        require("|" not in value and "\n" not in value.strip(),
                f"{where}: must be one line without '|' (it is shown in tables)")
    return value.strip()


def check_url(value, where: str) -> str:
    require(isinstance(value, str) and URL_RE.match(value) is not None, f"{where}: expected a URL")
    return value


def check_millennium(entries, problems: dict, where: str) -> list[dict]:
    require(isinstance(entries, list), f"{where}.millennium: expected a list (may be empty)")
    out = []
    for i, entry in enumerate(entries):
        w = f"{where}.millennium[{i}]"
        require(isinstance(entry, dict), f"{w}: expected a mapping")
        require(entry.get("problem") in problems,
                f"{w}.problem: unknown problem {entry.get('problem')!r}; known: {sorted(problems)}")
        require(entry.get("relation") in RELATIONS,
                f"{w}.relation: expected one of {sorted(RELATIONS)}")
        note = entry.get("note")
        if note is not None:
            check_text(note, f"{w}.note", table_safe=True)
        out.append({"problem": entry["problem"], "relation": entry["relation"], "note": note})
    return out


def load_problems() -> dict:
    data = load_yaml(PROBLEMS_DIR / "problems.yaml")
    problems = {}
    for i, p in enumerate(data):
        w = f"problems/problems.yaml[{i}]"
        require(SLUG_RE.match(str(p.get("id", ""))) is not None, f"{w}.id: expected a slug")
        check_text(p.get("name"), f"{w}.name", table_safe=True)
        require(p.get("status") in ("open", "solved"), f"{w}.status: expected open or solved")
        check_text(p.get("status_note"), f"{w}.status_note", table_safe=True)
        check_url(p.get("clay"), f"{w}.clay")
        page = PROBLEMS_DIR / f"{p['id']}.md"
        require(page.exists(), f"{w}: missing page {page.relative_to(ROOT)}")
        problems[p["id"]] = p
    return problems


def load_paper(meta_path: Path, problems: dict) -> dict:
    rel = meta_path.parent.relative_to(ROOT).as_posix()
    where = f"{rel}/paper.yaml"
    meta = load_yaml(meta_path)
    require(isinstance(meta, dict), f"{where}: expected a mapping")
    require("TODO" not in meta_path.read_text(encoding="utf-8"), f"{where}: still contains TODO placeholders")

    slug = meta.get("slug")
    require(isinstance(slug, str) and SLUG_RE.match(slug) is not None and len(slug) <= 60,
            f"{where}.slug: expected lowercase-kebab-case, at most 60 characters")
    date = as_date(meta.get("date"), f"{where}.date")
    expected_dir = f"papers/{date.year:04d}/{date.month:02d}/{slug}"
    require(rel == expected_dir, f"{where}: directory must be {expected_dir} (from date and slug)")

    authors = meta.get("authors")
    require(isinstance(authors, list) and authors and all(isinstance(a, str) and a for a in authors),
            f"{where}.authors: expected a non-empty list of names")
    paper = {
        "slug": slug,
        "path": rel,
        "title": check_text(meta.get("title"), f"{where}.title", table_safe=True),
        "short_title": check_text(meta.get("short_title", meta.get("title")), f"{where}.short_title",
                                  table_safe=True),
        "authors": authors,
        "date": date.isoformat(),
        "first_version": as_date(meta.get("first_version", date), f"{where}.first_version").isoformat(),
        "tldr": check_text(meta.get("tldr"), f"{where}.tldr", table_safe=True),
        "millennium": check_millennium(meta.get("millennium"), problems, where),
        "fields": meta.get("fields") or [],
        "tags": meta.get("tags") or [],
    }
    for key in ("fields", "tags"):
        require(isinstance(paper[key], list) and all(isinstance(t, str) and SLUG_RE.match(t)
                                                     for t in paper[key]),
                f"{where}.{key}: expected a list of lowercase-kebab-case words")

    status = meta.get("status") or {}
    require(status.get("review") in REVIEW, f"{where}.status.review: expected one of {sorted(REVIEW)}")
    require(status.get("formalization") in FORMALIZATION,
            f"{where}.status.formalization: expected one of {sorted(FORMALIZATION)}")
    require(status.get("community") in COMMUNITY,
            f"{where}.status.community: expected one of {sorted(COMMUNITY)}")
    if status.get("formalization") != "none":
        check_text(status.get("formalization_system"), f"{where}.status.formalization_system",
                   table_safe=True)
    as_date(status.get("as_of"), f"{where}.status.as_of")
    paper["status"] = {k: (v.isoformat() if isinstance(v, dt.date) else v) for k, v in status.items()}

    links = meta.get("links") or {}
    check_url(links.get("paper"), f"{where}.links.paper")
    for key, value in links.items():
        if key == "related":
            require(isinstance(value, list), f"{where}.links.related: expected a list")
            for j, item in enumerate(value):
                check_text(item.get("label"), f"{where}.links.related[{j}].label", table_safe=True)
                check_url(item.get("url"), f"{where}.links.related[{j}].url")
        else:
            check_url(value, f"{where}.links.{key}")
    paper["links"] = links

    explainer = meta.get("explainer") or {}
    as_date(explainer.get("added"), f"{where}.explainer.added")
    for key in ("video", "poster", "code", "figures"):
        if explainer.get(key):
            target = meta_path.parent / explainer[key]
            require(target.exists(), f"{where}.explainer.{key}: {explainer[key]} does not exist")
    if explainer.get("video_url"):
        check_url(explainer["video_url"], f"{where}.explainer.video_url")
    checks = explainer.get("checks") or []
    require(isinstance(checks, list) and all(isinstance(c, str) and c.strip() for c in checks),
            f"{where}.explainer.checks: expected a list of shell-free commands")
    paper["explainer"] = {k: (v.isoformat() if isinstance(v, dt.date) else v)
                          for k, v in explainer.items()}
    require((meta_path.parent / "README.md").exists(), f"{rel}: missing README.md (the explainer)")
    return paper


def load_backlog(problems: dict) -> list[dict]:
    path = ROOT / "backlog.yaml"
    if not path.exists():
        return []
    items = load_yaml(path) or []
    out = []
    for i, item in enumerate(items):
        w = f"backlog.yaml[{i}]"
        require(isinstance(item, dict), f"{w}: expected a mapping")
        out.append({
            "title": check_text(item.get("title"), f"{w}.title", table_safe=True),
            "authors": item.get("authors") or [],
            "date": as_date(item.get("date"), f"{w}.date").isoformat(),
            "millennium": check_millennium(item.get("millennium"), problems, w),
            "url": check_url(item.get("url"), f"{w}.url"),
            "note": check_text(item.get("note"), f"{w}.note", table_safe=True),
            "links": [{"label": check_text(l.get("label"), f"{w}.links.label", table_safe=True),
                       "url": check_url(l.get("url"), f"{w}.links.url")}
                      for l in (item.get("links") or [])],
        })
    return out


def load_all() -> tuple[dict, list[dict], list[dict]]:
    problems = load_problems()
    papers, errors = [], []
    for meta_path in sorted(PAPERS.glob("*/*/*/paper.yaml")):
        try:
            papers.append(load_paper(meta_path, problems))
        except ValidationError as exc:
            errors.append(str(exc))
    for d in sorted(PAPERS.glob("*/*/*")):
        if d.is_dir() and not (d / "paper.yaml").exists():
            errors.append(f"{d.relative_to(ROOT).as_posix()}: missing paper.yaml")
    seen: dict[str, str] = {}
    for p in papers:
        if p["slug"] in seen:
            errors.append(f"duplicate slug {p['slug']!r}: {seen[p['slug']]} and {p['path']}")
        seen[p["slug"]] = p["path"]
    try:
        backlog = load_backlog(problems)
    except ValidationError as exc:
        errors.append(str(exc))
        backlog = []
    if errors:
        raise ValidationError("\n".join(errors))
    papers.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)
    return problems, papers, backlog


